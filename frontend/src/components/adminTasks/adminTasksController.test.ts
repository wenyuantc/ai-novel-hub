function visibility() {
  const target = new EventTarget()
  const state = { visibilityState: 'visible' as DocumentVisibilityState,
    addEventListener: (type: 'visibilitychange', listener: () => void) => target.addEventListener(type, listener),
    removeEventListener: (type: 'visibilitychange', listener: () => void) => target.removeEventListener(type, listener),
  }
  return { target, state }
}
describe('5秒轮询开关与可见性', () => {
  it('默认5秒、hidden暂停、visible立即更新，停止后计时器和监听都移除', () => {
    vi.useFakeTimers()
    const v = visibility(); const refresh = vi.fn()
    const stop = startDashboardPolling(refresh, v.state, 5_000)
    vi.advanceTimersByTime(4_999); expect(refresh).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1); expect(refresh).toHaveBeenCalledTimes(1)
    v.state.visibilityState = 'hidden'; v.target.dispatchEvent(new Event('visibilitychange'))
    expect(vi.getTimerCount()).toBe(0)
    vi.advanceTimersByTime(20_000); expect(refresh).toHaveBeenCalledTimes(1)
    v.state.visibilityState = 'visible'; v.target.dispatchEvent(new Event('visibilitychange'))
    expect(refresh).toHaveBeenCalledTimes(2)
    stop(); expect(vi.getTimerCount()).toBe(0)
    v.target.dispatchEvent(new Event('visibilitychange')); vi.advanceTimersByTime(20_000)
    expect(refresh).toHaveBeenCalledTimes(2)
  })
})
