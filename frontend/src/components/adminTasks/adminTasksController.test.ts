function loaders() {
  return {
    list: vi.fn<typeof adminTasksApi.list>(async () => list()),
    get: vi.fn<typeof adminTasksApi.get>(async (key) => detail({ task_key: key })),
    cancel: vi.fn<typeof adminTasksApi.cancel>(async () => ({ operation_id: 'operation-1', audit_log_id: 9 })),
    owners: vi.fn<typeof adminApi.listUsers>(async () => ({ items: [], total: 0 })),
  }
}
function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (error: unknown) => void
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no })
  return { promise, resolve, reject }
}
async function settled() { for (let i = 0; i < 12; i += 1) await Promise.resolve() }
